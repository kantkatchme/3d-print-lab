#!/usr/bin/env python3
"""Filament demand of the print queue vs. what is on the shelf.

Reads grams / material / nozzle from the header comments of every G-code file below
$PRINT_DIR/queue/ (OrcaSlicer / Elegoo Slicer write them), compares the demand per material with the
stock table in $PRINT_DIR/filament-stock.md and writes $PRINT_DIR/filament-demand.md.

stdout: one warning line per shortage, nothing otherwise (handy for a daily digest).

Layout:  $PRINT_DIR/queue/<person>/<project>/*.gcode
Stock:   a markdown table with the columns  Type | Color | New | Opened | Remaining
         where "Remaining" is e.g. `750 g` or `0.8 kg` (rows without it are ignored). See examples/filament-stock.md
"""
import os
import re
from datetime import datetime
from pathlib import Path

D = Path(os.environ.get("PRINT_DIR") or ".")
QUEUE = D / "queue"
STOCK = D / "filament-stock.md"
REPORT = D / "filament-demand.md"
RESERVE = 1.10  # 10 % margin (failed prints, purging, remainders on the spool)


def header(path):
    """Grams, material and nozzle from the G-code comment block."""
    g = mat = noz = None
    with open(path, "rb") as fh:
        for raw in fh:
            if not raw.startswith(b";"):
                continue
            line = raw.decode("utf-8", "ignore")
            if g is None and line.startswith("; total filament used [g]"):
                g = float(line.split("=")[1])
            elif mat is None and line.startswith("; filament_type ="):
                mat = line.split("=")[1].strip().split(";")[0]
            elif noz is None and line.startswith("; nozzle_diameter ="):
                noz = line.split("=")[1].strip().split(",")[0]
            if g is not None and mat and noz:
                break
    return g or 0.0, mat or "?", noz or "?"


def stock():
    """Remaining grams per material type (summed over all spools of that type)."""
    out = {}
    if not STOCK.exists():
        return out
    for row in STOCK.read_text().splitlines():
        c = [x.strip() for x in row.strip().strip("|").split("|")]
        if len(c) < 5 or not c[4]:
            continue
        n = re.search(r"([\d.,]+)\s*(kg|g)", c[4].lower())
        if n:
            v = float(n.group(1).replace(",", "."))
            key = c[0].upper().replace("MATTE ", "").replace("RAPID ", "").replace("+", "")
            out[key] = out.get(key, 0) + (v * 1000 if n.group(2) == "kg" else v)
    return out


jobs = []
for f in sorted(QUEUE.rglob("*.gcode")):
    g, mat, noz = header(f)
    parts = f.relative_to(QUEUE).parts
    jobs.append((parts[0], f.parent.name, f.stem, g, mat.upper(), noz))

demand = {}
for *_, g, mat, _ in jobs:
    demand[mat] = demand.get(mat, 0) + g
have = stock()

rows, warn = [], []
for mat, g in sorted(demand.items()):
    avail = have.get(mat)
    if avail is None:
        status = "stock not recorded"
    elif avail < g * RESERVE:
        status = f"⚠️ short by ≈ {g * RESERVE - avail:.0f} g"
        warn.append(f"{mat}: queue needs ≈ {g:.0f} g (+{int((RESERVE - 1) * 100)} % margin), only {avail:.0f} g on hand")
    else:
        status = "✅ enough"
    rows.append(f"| {mat} | {g:.0f} g | {f'{avail:.0f} g' if avail is not None else '–'} | {status} |")

per_person, per_nozzle = {}, {}
for person, *_, g, _, noz in jobs:
    per_person[person] = per_person.get(person, 0) + g
    per_nozzle[noz] = per_nozzle.get(noz, 0) + g

md = [
    "# Filament demand of the print queue",
    f"> Generated by `filament_demand.py` on {datetime.now():%Y-%m-%d %H:%M}. Warns only if demand + "
    f"{int((RESERVE - 1) * 100)} % margin exceeds stock. Don't edit by hand.",
    "", "## Demand vs. stock", "| Material | Demand | Stock | Status |", "|---|---|---|---|", *rows,
    "", "## By person", *[f"- {p}: {g:.0f} g" for p, g in sorted(per_person.items())],
    "", "## By nozzle", *[f"- {n} mm: {g:.0f} g" for n, g in sorted(per_nozzle.items())],
    "", "## All jobs", "| Person | Project | File | Material | Nozzle | Grams |", "|---|---|---|---|---|---|",
    *[f"| {p} | {pr} | {s[:60]} | {m} | {n} | {g:.0f} |" for p, pr, s, g, m, n in jobs],
    f"| | | **Total** | | | **{sum(j[3] for j in jobs):.0f}** |", "",
]
REPORT.write_text("\n".join(md))
if warn:
    print("Filament shortage: " + "; ".join(warn))
